#!/usr/bin/env node
// Laptop-side one-shot. Given a persona slug, pull the DB profile and
// generate every filesystem artifact the daemons still read locally:
//
//   1. site-monitor/personas/{slug}.json        (legacy JSON — daemon fallback)
//   2. vaults/{slug}/README.md                  (Obsidian identity card)
//   3. site-monitor/launchd/ai.openclaw.{slug}.site-review.plist  (LaunchAgent)
//   4. Prints .env keys to paste into site-monitor/.env
//
// Run on the laptop host (the one that polls AgentMail + runs site-review):
//
//   node scripts/persona-bootstrap-export.mjs <slug>
//
// Requires DATABASE_URL_UNPOOLED (or DATABASE_URL) in the shell env so the
// script can read from Neon. The generated files are idempotent — safe to
// re-run after profile edits to pick up the latest shape.

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { neon } from '@neondatabase/serverless';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..');

function die(msg) {
  console.error(msg);
  process.exit(1);
}

const slug = process.argv[2];
if (!slug) die('Usage: node scripts/persona-bootstrap-export.mjs <slug>');

const dbUrl = process.env.DATABASE_URL_UNPOOLED ?? process.env.DATABASE_URL;
if (!dbUrl) die('DATABASE_URL_UNPOOLED or DATABASE_URL not set');

const sql = neon(dbUrl);
const rows =
  await sql`SELECT slug, name, short, profile FROM persona WHERE slug = ${slug} LIMIT 1`;
if (rows.length === 0) die(`Persona "${slug}" not found in DB`);

const row = rows[0];
const profile = row.profile;
if (!profile) die(`Persona "${slug}" has no profile — edit it in /admin/personas first`);
const id = profile.identity;
const j = profile.journey;
const am = profile.agentmail;

// ─── 1. site-monitor/personas/{slug}.json ─────────────────────────────────

const legacyJson = {
  name: id.name,
  age: id.age,
  generation: id.generation,
  gender: id.gender,
  style: id.style,
  shopping_habits: id.shopping_habits,
  tech_comfort: id.tech_comfort,
  focus_areas: id.focus_areas ?? [],
  search_term: j.search_term ?? '',
  category_path: j.category_path ?? [],
  site: j.site ?? '',
  credentials_env_prefix: j.credentials_env_prefix ?? '',
};
const legacyPath = path.join(REPO, 'site-monitor', 'personas', `${slug}.json`);
fs.mkdirSync(path.dirname(legacyPath), { recursive: true });
fs.writeFileSync(legacyPath, JSON.stringify(legacyJson, null, 2) + '\n');
console.log(`  wrote ${path.relative(REPO, legacyPath)}`);

// ─── 2. vaults/{slug}/README.md ───────────────────────────────────────────

const gender = String(id.gender || 'other').toLowerCase();
const categoryPath = (j.category_path ?? []).join(' > ');
const readme = `---
slug: ${slug}
name: ${id.name}
age: ${id.age}
generation: ${id.generation}
gender: ${id.gender}
---

# ${id.name}

${id.age} · ${id.generation} · ${gender} — ${id.style}

## Focus areas
${(id.focus_areas ?? []).map((f) => `- ${f}`).join('\n')}

## Shopping habits
${id.shopping_habits}

## Tech comfort
${id.tech_comfort}

## Journey hints
- Primary search term: \`${j.search_term ?? ''}\`
- Category path: ${categoryPath || '—'}
- Site: ${j.site ?? '—'}

${profile.notes ? `\n## Notes\n${profile.notes}\n` : ''}---

Auto-generated by scripts/persona-bootstrap-export.mjs from the DB profile.
Edits here are fine as human-maintained notes; re-running the script
overwrites this file.
`;
const vaultDir = path.join(REPO, 'vaults', slug);
const readmePath = path.join(vaultDir, 'README.md');
fs.mkdirSync(vaultDir, { recursive: true });
fs.mkdirSync(path.join(vaultDir, 'audits'), { recursive: true });
fs.writeFileSync(readmePath, readme);
console.log(`  wrote ${path.relative(REPO, readmePath)}`);

// ─── 3. site-monitor/launchd/ai.openclaw.{slug}.site-review.plist ─────────

const launchdDir = path.join(REPO, 'site-monitor', 'launchd');
fs.mkdirSync(launchdDir, { recursive: true });
const plistPath = path.join(
  launchdDir,
  `ai.openclaw.${slug}.site-review.plist`
);
// Stagger start times so the 2+ personas don't contend for the single
// Chrome instance. Walker is 06:00 UTC (historical); offset +30m per slot.
const existingPlists = fs.readdirSync(launchdDir).filter((f) => f.endsWith('.plist'));
const minuteOffset = (existingPlists.length * 30) % 60;
const hour = 6 + Math.floor((existingPlists.length * 30) / 60);
const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>ai.openclaw.${slug}.site-review</string>
  <key>ProgramArguments</key>
  <array>
    <string>/usr/bin/env</string>
    <string>bash</string>
    <string>-c</string>
    <string>cd ${REPO}/site-monitor && /opt/homebrew/bin/node site-review.mjs --persona ${slug} &gt;&gt; logs/site-review.log 2&gt;&amp;1</string>
  </array>
  <key>StartCalendarInterval</key>
  <dict>
    <key>Hour</key><integer>${hour}</integer>
    <key>Minute</key><integer>${minuteOffset}</integer>
  </dict>
  <key>RunAtLoad</key><false/>
  <key>StandardErrorPath</key>
  <string>${REPO}/site-monitor/logs/${slug}-site-review-stderr.log</string>
  <key>StandardOutPath</key>
  <string>${REPO}/site-monitor/logs/${slug}-site-review-stdout.log</string>
</dict>
</plist>
`;
fs.writeFileSync(plistPath, plist);
console.log(`  wrote ${path.relative(REPO, plistPath)}`);

// ─── 4. Print .env keys ───────────────────────────────────────────────────

const envPrefix = j.credentials_env_prefix || `PERSONA_${slug.toUpperCase()}`;
const inbox = am.inbox_address || `${slug}@agentmail.to`;

console.log('');
console.log('─── Next steps (laptop) ──────────────────────────────────────────');
console.log('');
console.log('1. Paste into site-monitor/.env:');
console.log('');
console.log(`     ${envPrefix}_EMAIL=${inbox}`);
console.log(`     ${envPrefix}_PASSWORD=<generated-password>`);
console.log('');
console.log('2. Capture login cookies once:');
console.log('');
console.log(`     cd site-monitor && node save-cookies.mjs --persona ${slug}`);
console.log('');
console.log('3. Install the LaunchAgent:');
console.log('');
console.log(`     cp ${path.relative(REPO, plistPath)} ~/Library/LaunchAgents/`);
console.log(
  `     launchctl bootstrap gui/$(id -u) ~/Library/LaunchAgents/ai.openclaw.${slug}.site-review.plist`
);
console.log('');
console.log('4. Restart email-monitor to pick up the new inbox:');
console.log('');
console.log(
  '     launchctl bootout gui/$(id -u) ~/Library/LaunchAgents/com.walker.agentmail-monitor.plist'
);
console.log(
  '     launchctl bootstrap gui/$(id -u) ~/Library/LaunchAgents/com.walker.agentmail-monitor.plist'
);
console.log('');
console.log('Done. New audits will start rolling in on the next poll cycle.');
